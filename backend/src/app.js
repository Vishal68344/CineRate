import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import authRoutes from './routes/auth.js';
import movieRoutes from './routes/movies.js';
import reviewRoutes from './routes/reviews.js';
import {errorHandler} from './middleware/errorHandler.js';
export const app=express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({origin:process.env.FRONTEND_URL?.split(',')||'http://localhost:5173'}));
app.use(express.json({limit:'32kb'}));
app.get('/api/health',(req,res)=>res.json({status:'ok',service:'cinerate-api'}));
app.use('/api/auth',rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:'draft-7',legacyHeaders:false}),authRoutes);
app.use('/api/movies',movieRoutes);
app.use('/api',reviewRoutes);
app.use((req,res)=>res.status(404).json({error:'Route not found'}));
app.use(errorHandler);
